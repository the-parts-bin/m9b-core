#!/usr/bin/env python3
# Convert a raw little-endian binary image into a $readmemh file holding
# one hex word per line (32-bit by default), padded to `words` entries.
# With word_bytes = 8, the output is instead a Verilog include of INIT_RAM
# defparams for rtl/ram64.v's four SDPB blocks.
import sys

def main():
    if len(sys.argv) not in (4, 5):
        sys.exit(f"usage: {sys.argv[0]} <in.bin> <out.hex> <words> [word_bytes]")

    in_path, out_path, words = sys.argv[1], sys.argv[2], int(sys.argv[3])
    wb = int(sys.argv[4]) if len(sys.argv) == 5 else 4

    with open(in_path, "rb") as f:
        data = f.read()

    if len(data) > words * wb:
        sys.exit(f"error: firmware ({len(data)} bytes) does not fit in "
                  f"{words * wb} bytes of RAM")

    data += b"\x00" * (words * wb - len(data))

    # 64-bit words (rtl/ram64.v's boot RAM) are written as INIT_RAM
    # defparams for its four 512 x 32-bit SDPB blocks, lo0/lo1 (low halves
    # of words 0..511 / 512..1023) and hi0/hi1, into <out_path>
    # (boot_ram_init.vh). INIT_RAM_nn holds words 8nn..8nn+7, word 8nn in
    # bits 31:0.
    if wb == 8:
        halves = {"lo": [], "hi": []}
        for i in range(words):
            word = int.from_bytes(data[i * 8:i * 8 + 8], "little")
            halves["lo"].append(word & 0xffffffff)
            halves["hi"].append(word >> 32)
        with open(out_path, "w") as f:
            f.write("// Generated by firmware/makehex.py: boot RAM contents.\n")
            for name in ("lo", "hi"):
                for blk in range(2):
                    ws = halves[name][512 * blk:512 * (blk + 1)]
                    for n in range(64):
                        v = 0
                        for k in range(8):
                            v |= ws[8 * n + k] << (32 * k)
                        f.write(f"defparam {name}{blk}.INIT_RAM_{n:02X} = 256'h{v:064X};\n")
        return

    with open(out_path, "w") as f:
        for i in range(words):
            word = int.from_bytes(data[i * wb:i * wb + wb], "little")
            f.write(f"{word:0{2 * wb}x}\n")

if __name__ == "__main__":
    main()
