#!/usr/bin/env python3
# Writes vexii_mem_init.vh: zeroes every memory in rtl/VexiiRiscv.v at time
# 0 (included by tb_soc.v). On the FPGA they power up as zero; in a 4-state
# simulator they start as X, which reaches the PC through branch prediction.
# Rerun after regenerating the core.
import os
import re

here = os.path.dirname(os.path.abspath(__file__))
v = open(os.path.join(here, "../rtl/VexiiRiscv.v")).read()

def memories(module):
    body = v[v.index(f"module {module} ("):]
    body = body[:body.index("endmodule")]
    return re.findall(r"reg\s+\[\d+:0\]\s+(\w+)\s+\[0:(\d+)\]\s*(?:/\*.*?\*/)?\s*;", body)

lines = [
    "// Generated by gen_vexii_mem_init.py from the memory declarations in",
    "// rtl/VexiiRiscv.v: zeroes the CPU's memories at time 0. On the FPGA they",
    "// power up as zero; in a 4-state simulator they start as X, which reaches",
    "// the PC through branch prediction.",
    "integer vexii_init_i;",
    "initial begin",
]
for path, module in (("dut.CPU", "VexiiRiscv"),
                     ("dut.CPU.integer_RegFilePlugin_logic_regfile_fpga", "RegFileMem")):
    for name, depth in memories(module):
        lines.append(f"  for (vexii_init_i = 0; vexii_init_i <= {depth}; "
                     f"vexii_init_i = vexii_init_i + 1) {path}.{name}[vexii_init_i] = 0;")
# Memories that VexiiRiscv.v hands to rtl/Ram_1w_1rs.v (--blackbox-byte-enables):
# those on its inferred path hold a plain array (the SDPB ones start as zero).
top = v[v.index("module VexiiRiscv ("):]
top = top[:top.index("endmodule")]
for params, inst in re.findall(r"Ram_1w_1rs #\((.*?)\)\s*(\w+)\s*\(", top, re.S):
    p = dict(re.findall(r"\.(\w+)\s*\(\s*([^)\s]+)\s*\)", params))
    if (p["wordWidth"], p["wrMaskWidth"]) == ("64", "8") and int(p["wordCount"]) <= 1024:
        continue
    lines.append(f"  for (vexii_init_i = 0; vexii_init_i < {p['wordCount']}; "
                 f"vexii_init_i = vexii_init_i + 1) dut.CPU.{inst}.inferred.mem[vexii_init_i] = 0;")
lines.append("end")
open(os.path.join(here, "vexii_mem_init.vh"), "w").write("\n".join(lines) + "\n")
