#!/usr/bin/env python3
"""Writes usb_hid_host_rom.v from usb_hid_host_rom.hex: the USB core's
microcode (536 x 4 bits) in one pROM block, as a primitive with INIT_RAM_xx
values."""
import os

here = os.path.dirname(os.path.abspath(__file__))
words = [int(l, 16) for l in open(os.path.join(here, "usb_hid_host_rom.hex")) if l.strip()]
bits = 0
for i, w in enumerate(words):
    bits |= (w & 0xF) << (4 * i)
n_init = (4 * len(words) + 255) // 256
init = "\n".join(f"    .INIT_RAM_{k:02X}(256'h{(bits >> (256 * k)) & ((1 << 256) - 1):064x})," for k in range(n_init))

open(os.path.join(here, "usb_hid_host_rom.v"), "w").write(f"""// Generated by gen_usb_rom.py from usb_hid_host_rom.hex: the USB host
// core's microcode (usb_hid_host.v's ukp, {len(words)} x 4 bits) in one pROM.
// Registered read, like the original ROM.
module usb_hid_host_rom (
    input  wire        clk,
    input  wire [9:0]  adr,
    output wire [3:0]  data
);
  wire [31:0] dout;
  assign data = dout[3:0];
  pROM #(
    .READ_MODE(1'b0),
    .BIT_WIDTH(4),
{init}
    .RESET_MODE("SYNC")
  ) rom (
    .DO(dout), .CLK(clk), .OCE(1'b1), .CE(1'b1), .RESET(1'b0),
    .AD({{2'b00, adr, 2'b00}})
  );
endmodule
""")
