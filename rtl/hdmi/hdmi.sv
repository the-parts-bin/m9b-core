// Implementation of HDMI Spec v1.4a
// Based on original implementation by Sameer Puri https://github.com/sameer

module hdmi(
    input logic clk_pixel_x5,
    input logic clk_pixel,
    // synchronous reset back to 0,0
    input logic reset,
    // reset for the TMDS serializers (OSER10), kept separate so it can come
    // from the same place as before the move to the pixel clock
    input logic serializer_reset,
    input logic [23:0] rgb,

    // Audio data
    input logic [15:0] audio_sample_data[1:0] [1:0],
    input logic [6:0] audio_frame_counter,
    input logic audio_sample_ready,
    output logic audio_sample_used,

    // These outputs go to your HDMI port
    output logic [2:0] tmds,
    output logic tmds_clock,
    
    // All outputs below this line stay inside the FPGA
    // They are used (by you) to pick the color each pixel should have
    // i.e. always_ff @(posedge pixel_clk) rgb <= {8'd0, 8'(cx), 8'(cy)};
    output logic [11:0] cx,
    output logic [9:0] cy,
    output logic [9:0] cy_next
);
  logic hsync;
  logic vsync;

  // Format 2 from CEA-861-D for more specifics formats described below.
  logic [11:0]frame_width;
  logic [11:0]screen_width;
  logic [11:0]hsync_pulse_start;
  logic [11:0]hsync_pulse_size;
  logic [9:0]frame_height;
  logic [9:0]screen_height;
  logic [9:0]vsync_pulse_start;
  logic [9:0]vsync_pulse_size;
  logic invert;

  // 720 x 480 59.94 Hz (CEA-861 format 2/3), 27 MHz pixel clock
  assign frame_width = 858;
  assign frame_height = 525;
  assign screen_width = 720;
  assign screen_height = 480;
  assign hsync_pulse_start = 16;
  assign hsync_pulse_size = 62;
  assign vsync_pulse_start = 9;
  assign vsync_pulse_size = 6;
  assign invert = 1;

  // One cycle per pixel (clk_pixel): cx is the pixel position.
  logic [10:0]rcx;
  assign rcx = cx[10:0];

  always_comb begin
    hsync <= invert ^ (rcx >= screen_width + hsync_pulse_start && rcx < screen_width + hsync_pulse_start + hsync_pulse_size);
    // vsync pulses should begin and end at the start of hsync, so special
    // handling is required for the lines on which vsync starts and ends
    if (cy == screen_height + vsync_pulse_start)
      vsync <= invert ^ (rcx >= screen_width + hsync_pulse_start);
    else if (cy == screen_height + vsync_pulse_start + vsync_pulse_size)
      vsync <= invert ^ (rcx < screen_width + hsync_pulse_start);
    else
      vsync <= invert ^ (cy >= screen_height + vsync_pulse_start && cy < screen_height + vsync_pulse_start + vsync_pulse_size);
  end

  // Wrap-around pixel position counters indicating the pixel to be generated by the user in THIS clock and sent out in the NEXT clock.
  always_ff @(posedge clk_pixel) begin
    if (reset) begin
      cx <= 12'd0;
      cy <= 10'd0;
      cy_next <= 10'd1;
    end else begin
      if(cx == frame_width - 1) begin
        cx <= 0;
        cy <= cy_next;
        if (cy_next == frame_height - 1) begin
          cy_next <= 0;  
        end else begin
          cy_next <= cy_next + 1'b1;  
        end
      end else begin
        cx <= cx + 1'b1;
      end
    end
  end

  // See Section 5.2
  logic video_data_period = 0;
  always_ff @(posedge clk_pixel) begin
    if (reset)
      video_data_period <= 0;
    else
      video_data_period <= rcx < screen_width && cy < screen_height;
  end

  logic [2:0] mode = 3'd1;
  logic [23:0] video_data = 24'd0;
  logic [5:0] control_data = 6'd0;
  logic [11:0] data_island_data = 12'd0;
  logic video_guard = 1;
  logic video_preamble = 0;
  always_ff @(posedge clk_pixel) begin
    if (reset) begin
      video_guard <= 1;
      video_preamble <= 0;
    end else begin
      video_guard <= rcx >= frame_width - 2 && rcx < frame_width && (cy == frame_height - 1 || cy < screen_height);
      video_preamble <= rcx >= frame_width - 10 && rcx < frame_width - 2 && (cy == frame_height - 1 || cy < screen_height);
    end
  end

  // See Section 5.2.3.1
  const int NUM_PACKETS = 3;

  logic data_island_period_instantaneous;
  assign data_island_period_instantaneous = rcx >= screen_width + 10 && rcx < screen_width + 10 + NUM_PACKETS * 32;
  logic packet_enable;
  assign packet_enable = data_island_period_instantaneous && 5'(rcx + screen_width + 22) == 5'd0;

  logic data_island_guard = 0;
  logic data_island_preamble = 0;
  logic data_island_period = 0;
  always_ff @(posedge clk_pixel) begin
    if (reset) begin
      data_island_guard <= 0;
      data_island_preamble <= 0;
      data_island_period <= 0;
    end else begin
      data_island_guard <= ((rcx >= screen_width + 8 && rcx < screen_width + 10) || (rcx >= screen_width + 10 + NUM_PACKETS * 32 && rcx < screen_width + 10 + NUM_PACKETS * 32 + 2));
      data_island_preamble <= rcx >= screen_width && rcx < screen_width + 8;
      data_island_period <= data_island_period_instantaneous;
    end
  end

  // See Section 5.2.3.4
  logic [23:0] header;
  logic [55:0] sub [3:0];
  logic video_field_end;
  assign video_field_end = rcx == screen_width - 1'b1 && cy == screen_height - 1'b1;
  logic [4:0] packet_pixel_counter;
  packet_picker pp (
    .system_clk(clk_pixel),
    .reset(reset),
    .video_field_end(video_field_end),
    .packet_enable(packet_enable),
    .packet_pixel_counter(packet_pixel_counter),
    .audio_sample_data(audio_sample_data),
    .audio_sample_ready(audio_sample_ready),
    .audio_sample_used(audio_sample_used),
    .audio_frame_counter(audio_frame_counter),
    .header(header), .sub(sub));
  logic [8:0] packet_data;
  packet_assembler packet_assembler (
    .system_clk(clk_pixel),
    .reset(reset),
    .data_island_period(data_island_period),
    .header(header),
    .sub(sub),
    .packet_data(packet_data),
    .counter(packet_pixel_counter)
  );

  always_ff @(posedge clk_pixel) begin
    if (reset) begin
      mode <= 3'd2;
      video_data <= 24'd0;
      control_data = 6'd0;
      data_island_data <= 12'd0;
    end else begin
      mode <= data_island_guard ? 3'd4 : data_island_period ? 3'd3 : video_guard ? 3'd2 : video_data_period ? 3'd1 : 3'd0;
      video_data <= rgb;
      control_data <= {{1'b0, data_island_preamble}, {1'b0, video_preamble || data_island_preamble}, {vsync, hsync}}; // ctrl3, ctrl2, ctrl1, ctrl0, vsync, hsync
      data_island_data[11:4] <= packet_data[8:1];
      data_island_data[3] <= rcx != 0;
      data_island_data[2] <= packet_data[0];
      data_island_data[1:0] <= {vsync, hsync};
    end
  end

  // All logic below relates to the production and output of the 10-bit TMDS code.
  logic [9:0] tmds_internal [2:0] /* verilator public_flat */ ;
  genvar i;
  generate
    // TMDS code production.
    for (i = 0; i < 3; i++)
    begin: tmds_gen
      tmds_channel #(.CN(i)) tmds_channel (
        .clk_pixel(clk_pixel), 
        .video_data(video_data[i*8+7:i*8]), 
        .data_island_data(data_island_data[i*4+3:i*4]), 
        .control_data(control_data[i*2+1:i*2]), 
        .mode(mode), 
        .tmds(tmds_internal[i])
      );
    end
  endgenerate

  serializer serializer(  
    .clk_pixel(clk_pixel), 
    .clk_pixel_x5(clk_pixel_x5), 
    .reset(serializer_reset), 
    .tmds_internal(tmds_internal), 
    .tmds(tmds), 
    .tmds_clock(tmds_clock)
  );

endmodule
